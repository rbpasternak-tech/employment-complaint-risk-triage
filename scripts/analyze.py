import json,csv,collections
# 003a: normalize legacy values from raw_labels.json
N=lambda v: None if v is None else ("not_reached" if v=="not_decided_on_12b6" else v.lower().replace(" ","_").replace("-","_"))
R=json.load(open("raw_labels.json"));P={"decisions":0.10,"jev":0.042}
rc={x["id"]:x for x in (json.load(open("recap.json")) if __import__("os").path.exists("recap.json") else [])}
sc=json.load(open("search_counts.json"))
lab=[];rev=[];C=collections.Counter
ag=C();n=0;tok=C();err=C()
for r in R:
    d=N(r["decisions"].get("out"));j=N(r["jev"].get("out"));h=N(r["heuristic"])
    for k in P:
        if "error" in r[k]: err[k]+=1
        else: tok[k]+=r[k]["tok"]
    if d and j:
        n+=1;ag["dj"]+=d==j
    if d and h: ag["dh_n"]+=1;ag["dh"]+=d==h
    if j and h: ag["jh_n"]+=1;ag["jh"]+=j==h
    auto=bool(d and d==j==h)
    rr=rc.get(r["id"],{})
    lab.append({k:r[k] for k in ["id","case_name","court","date_filed","url","docket_id","search_bucket"]}|{"search_bucket":N(r["search_bucket"]),"decisions_outcome":d,"jev_outcome":j,"heuristic_outcome":h,
      "decisions_claim_type":N(r["decisions"].get("ct")),"jev_claim_type":N(r["jev"].get("ct")),"auto_accepted":auto,
      "outcome_final":d if auto else None,"label_status":"auto_accepted" if auto else "review","dispositive_excerpt":r["dispositive_excerpt"],"recap_mtd_free":rr.get("mtd_free")})
    if not auto: rev.append(lab[-1])
json.dump(lab,open("labels.json","w"),indent=1)
with open("review.csv","w",newline="") as f:
    w=csv.writer(f);w.writerow(["id","case_name","court","date","url","decisions_outcome","jev_outcome","heuristic_outcome","decisions_claim_type","jev_claim_type","dispositive_excerpt","reviewer_outcome"])
    for x in rev: w.writerow([x["id"],x["case_name"],x["court"],x["date_filed"],x["url"],x["decisions_outcome"],x["jev_outcome"],x["heuristic_outcome"],x["decisions_claim_type"],x["jev_claim_type"],x["dispositive_excerpt"],""])
pct=lambda a,b:f"{a}/{b} ({100*a/b:.0f}%)" if b else "n/a"
auto=sum(x["auto_accepted"] for x in lab);rv=[x for x in rc.values() if "error" not in x];free=sum(bool(x.get("mtd_free")) for x in rv)
cost={k:tok[k]*P[k]/1e6 for k in P}
md=f"""# Employment class-action 12(b)(6) outcome labeling — batch 1
Generated by analyze.py. Opinions: federal district courts, 2023–2025, CourtListener.

## Search volume (opinions, all courts, 2023–2025)
Base: `{sc['query_base']}`
""" + "\n".join(f"- {k}: {v}" for k,v in sc["counts"].items()) + f"""

## Sample
- Cases: {len(lab)}; courts: {dict(C(x['court'] for x in lab).most_common())}
- Search buckets: {dict(C(x['search_bucket'] for x in lab))}

## Agreement
- Decisions vs Jev (outcome): {pct(ag['dj'],n)}
- Decisions vs heuristic: {pct(ag['dh'],ag['dh_n'])}; Jev vs heuristic: {pct(ag['jh'],ag['jh_n'])} (heuristic fired on {sum(1 for r in R if r['heuristic'])}/{len(R)})
- All three agree → auto-accepted: {pct(auto,len(lab))}; to review: {len(rev)} (review.csv)
- Claim type Decisions vs Jev: {pct(sum(x['decisions_claim_type']==x['jev_claim_type'] for x in lab if x['decisions_claim_type']),sum(1 for x in lab if x['decisions_claim_type']))}

## Label distribution
- Decisions: {dict(C(x['decisions_outcome'] for x in lab))}
- Jev: {dict(C(x['jev_outcome'] for x in lab))}
- Heuristic: {dict(C(x['heuristic_outcome'] for x in lab))}
- Claim type (Decisions): {dict(C(x['decisions_claim_type'] for x in lab))}

## RECAP
- Motion to dismiss (or 12(b)(6) brief) free on RECAP: {pct(free,len(rv))}; docket check errors: {len(rc)-len(rv)}

## Cost
- Decisions: {tok['decisions']:,} input tokens ≈ ${cost['decisions']:.3f}; Jev: {tok['jev']:,} ≈ ${cost['jev']:.3f}; errors {dict(err)}
- CourtListener: free (token rate limits were the bottleneck).

## Next steps
1. Rebecca spot-checks review.csv (fill `your_label`) plus ~5 auto-accepted cases.
2. If RECAP coverage is low, use the motion/complaint where it exists, and redacted opinion background sections elsewhere.
3. Grow to 200–500 cases, loosening the date range, since 2023–2025 coverage is thin.
"""
open("REPORT.md","w").write(md);print(md)
